"use strict";
const assert=require('node:assert/strict');
const Nearby=require('../backend/src/campuspilot/web_assets/nearby.js');
const origin={longitude:0,latitude:0,coordinate_system:'GCJ02'};
const place=(id,lng,lat,system='GCJ02')=>({place_id:`synthetic:${id}`,name:`SYNTHETIC ${id}`,aliases:[],position:{longitude:lng,latitude:lat,coordinate_system:system}});
const pool=[place('far',0.01,0),place('near',0.001,0),place('unconverted',0,0,'WGS84'),place('invalid',NaN,0),{place_id:'synthetic:unknown',position:null}];
assert.deepEqual(Nearby.rank(origin,pool).map(x=>x.place.place_id),['synthetic:near','synthetic:far']);
assert.ok(Math.abs(Nearby.rank(origin,pool)[0].distance-111.2)<1);
assert.deepEqual(Nearby.rank({...origin,coordinate_system:'WGS84'},pool),[]);
assert.deepEqual(Nearby.rank({...origin,latitude:100},pool),[]);
assert.equal(Nearby.rank(origin,[place('same',0,0)])[0].distance,0);
const wings=[{name:'SYNTHETIC E1A',place_id:'synthetic:e1a',aliases:['E1A']},{name:'SYNTHETIC E2A',place_id:'synthetic:e2a',aliases:['E2A']}];
for(const text of ['E2A101在哪','ｅ２ａ１０１','东教 E2A-101']) assert.deepEqual(Nearby.match(wings,text).map(p=>p.place_id),['synthetic:e2a']);
assert.deepEqual(Nearby.match(wings,'E3A101'),[]);
assert.deepEqual(Nearby.match(wings,'E1A在哪').map(p=>p.place_id),['synthetic:e1a']);
console.log('Nearby coordinate/ranking/classroom boundaries passed; fixtures are synthetic.');
