def original_contracts(snapshot: KnowledgeSnapshot, original: dict) -> list[dict]:
    """Reproduce the superseded author draft for an audit when output/ was not retained."""
    sources = {s.source_id: s for s in snapshot.sources}
    rows = []
    for category, split, key, specs in GROUPS:
        source_id = "cdut:source:" + key
        chunks = [c for c in snapshot.chunks if c.source_id == source_id]
        revision = fingerprint(
            {
                "source": next(s for s in original["sources"] if s["source_id"] == source_id),
                "chunks": [c for c in original["chunks"] if c["source_id"] == source_id],
            }
        )
        raw_dir = SNAPSHOT.parent / "raw/official/documents" / key.removeprefix("official:")
        files = sorted(raw_dir.rglob("*.txt")) if raw_dir.is_dir() else []
        for question, quotes, behavior, forbidden in specs:
            case_id = f"kq-{len(rows) + 1:03d}"
